// Writes `src/generated/ses-source.ts`: the text of `ses/dist/ses.umd.min.js` as one exported
// string, which the sandbox prepends to the worker blob (plan 28 D17).
//
// `ses`'s `exports` map does not list `dist/ses.umd.min.js`, so neither Node nor Vite resolves
// `ses/dist/ses.umd.min.js` (`?raw` included). `ses/package.json` is exported: this script finds
// the package through it and reads the file from disk.
//
//   mise exec -- vp run @hellotimber/nokia-games-sandbox#generate
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const UMD = "dist/ses.umd.min.js";

export const SES_SOURCE_FILE = fileURLToPath(
  new URL("../src/generated/ses-source.ts", import.meta.url),
);

/** The generated module for the `ses` this package resolves. */
export function sesSourceModule(): string {
  const manifestPath = createRequire(import.meta.url).resolve("ses/package.json");
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8")) as {
    version: string;
    license: string;
  };
  const source = readFileSync(join(dirname(manifestPath), UMD), "utf8");
  return [
    `// Generated by scripts/ses-source.ts from ses@${manifest.version} ${UMD} (${manifest.license}).`,
    "// Do not edit: run `vp run @hellotimber/nokia-games-sandbox#generate`.",
    `export const SES_SOURCE: string = ${JSON.stringify(source)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const module = sesSourceModule();
  let previous = "";
  try {
    previous = readFileSync(SES_SOURCE_FILE, "utf8");
  } catch {
    // first run
  }
  if (previous === module) console.log(`${SES_SOURCE_FILE}: up to date`);
  else {
    mkdirSync(dirname(SES_SOURCE_FILE), { recursive: true });
    writeFileSync(SES_SOURCE_FILE, module);
    console.log(`wrote ${SES_SOURCE_FILE} (${module.length} characters)`);
  }
}
