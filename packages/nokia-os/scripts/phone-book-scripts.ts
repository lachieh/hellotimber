// Transcribe plan 19 Task 0's capture command logs for the acceptance scenarios (plan 19 Task 11).
//
//   mise exec -- vp run @hellotimber/nokia-os#phone-book-scripts /path/to/nokia-3310
//
// Reads `captures/scripts/v639-plan19-<section>.cap` (the exact command stream each capture
// section sent; `gen_v639_plan19.py`) and writes `scripts/generated/phone-book-scripts.ts`: each
// log's commands, one per line, without comments, indentation and `hex` (plan 18's
// `transcribe`), and each log's SIM fixture and setup (its header's `# sim:` and `# setup:`).
// Both setup includes become `include setup` (the replay's phone is virgin or factory by the
// log's setup); a log that boots another image starts with `image <file>`. Tests replay
// these streams (tests/support/phone-book.ts), so they never read `$REF`.
//
// Idempotent. Runs under Node's type stripping: imports only node:*, sibling scripts.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { transcribe } from "./messages-scripts.ts";

const PACKAGE = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(PACKAGE, "scripts/generated/phone-book-scripts.ts");

function fail(message: string): never {
  console.error(`phone-book-scripts: ${message}`);
  process.exit(1);
}

function header(log: string, field: string, file: string): string {
  const value = new RegExp(`^# ${field}: (\\S+)$`, "m").exec(log)?.[1];
  if (value === undefined) fail(`${file}: no "# ${field}:" line`);
  return value;
}

function main(): void {
  const root = process.argv[2];
  if (root === undefined) fail("usage: phone-book-scripts <path to nokia-3310>");
  const dir = join(resolve(root), "captures/scripts");
  if (!existsSync(dir)) fail(`missing ${dir}`);
  const include = join(dir, "v639-setup.inc");
  if (!existsSync(include)) fail(`missing ${include}`);
  const setupLines = transcribe(readFileSync(include, "utf8"), []);
  const scripts: Record<string, string> = {};
  const setups: Record<string, { sim: string; setup: string }> = {};
  for (const file of readdirSync(dir).sort()) {
    const section = /^v639-plan19-(.+)\.cap$/.exec(file)?.[1];
    if (section === undefined) continue;
    // The factory include is plan 16's image and clock; the replay seeds the factory state.
    const log = readFileSync(join(dir, file), "utf8").replace(
      /^(\s*)include \S*v639-factory-setup\.inc$/m,
      "$1include v639-setup.inc",
    );
    const sim = header(log, "sim", file);
    const setup = header(log, "setup", file);
    // A log that boots the persistence image starts with `image <file>` (transcribe's).
    scripts[`plan19/${section}`] = transcribe(log, setupLines).join("\n");
    setups[`plan19/${section}`] = { sim, setup: setup === "factory" ? "factory" : "virgin" };
  }
  if (Object.keys(scripts).length === 0) fail(`no v639-plan19-*.cap in ${dir}`);
  const text = [
    "// GENERATED by scripts/phone-book-scripts.ts from captures/scripts/v639-plan19-*.cap - do not edit",
    "// Plan 19 Task 0's capture command logs, one command per line (tests/support/phone-book.ts replays them).",
    "export const PHONE_BOOK_CAPTURE_SCRIPTS: Readonly<Record<string, string>> = {",
    ...Object.entries(scripts).map(
      ([name, body]) => `  ${JSON.stringify(name)}: ${JSON.stringify(body)},`,
    ),
    "};",
    "",
    "/** Each log's SIM fixture (`plan19/sims/<sim>.json`) and the state its phone starts in. */",
    "export const PHONE_BOOK_SCRIPT_SETUPS: Readonly<",
    '  Record<string, { readonly sim: string; readonly setup: "virgin" | "factory" }>',
    "> = {",
    ...Object.entries(setups).map(
      ([name, { sim, setup }]) =>
        `  ${JSON.stringify(name)}: { sim: ${JSON.stringify(sim)}, setup: ${JSON.stringify(setup)} },`,
    ),
    "};",
    "",
  ].join("\n");
  if (existsSync(OUT) && readFileSync(OUT, "utf8") === text) {
    console.log("phone-book-scripts: up to date");
    return;
  }
  writeFileSync(OUT, text);
  console.log(`phone-book-scripts: ${Object.keys(scripts).length} logs → ${OUT}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
