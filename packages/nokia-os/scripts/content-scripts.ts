// Transcribe plan 18c Task 0's capture command logs for its acceptance scenarios.
//
//   mise exec -- vp run @hellotimber/nokia-os#content-scripts /path/to/nokia-3310
//
// Reads `captures/scripts/v639-plan18c-<section>.cap` (the exact command stream each capture
// section sent; `gen_v639_plan18c.py`) and writes `scripts/generated/content-scripts.ts`: each
// log's commands, one per line, without comments, indentation and `hex` (a read that takes no
// emulated time), the setup include as `include setup`, and each log's starting state (its
// `# state:` header: `virgin`, `factory` or `seccode`). Tests replay these streams
// (tests/support/18c-content.ts), so they never read `$REF`.
//
// Idempotent. Runs under Node's type stripping: imports only node:*.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const PACKAGE = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(PACKAGE, "scripts/generated/content-scripts.ts");

/** The states a plan 18c log starts from (`gen_v639_plan18c.py`). */
export const CONTENT_STATES = ["virgin", "factory", "seccode"] as const;
export type ContentState = (typeof CONTENT_STATES)[number];

/** The setup includes the logs may name, by file. */
const INCLUDES: Readonly<Record<string, true>> = {
  "v639-setup.inc": true,
  "v639-factory-setup.inc": true,
};

function fail(message: string): never {
  throw new Error(`content-scripts: ${message}`);
}

/**
 * A log's commands and starting state: no comments, blank lines or `hex`; the setup include as
 * `include setup`; a scroll's shot count appended (`=<n>`, from `count`).
 */
export function transcribeContent(
  log: string,
  count: (prefix: string) => number,
): { readonly state: ContentState; readonly lines: string[] } {
  const state = /^# state: (\S+)$/m.exec(log)?.[1];
  if (state === undefined || !(CONTENT_STATES as readonly string[]).includes(state)) {
    fail(`a log without a known "# state:" header (${state ?? "none"})`);
  }
  const lines: string[] = [];
  for (const raw of log.split("\n")) {
    const line = raw.trim().replace(/\s+/g, " ");
    if (line === "" || line.startsWith("#") || line === "hex") continue;
    const [command, ...args] = line.split(" ");
    if (command === "include") {
      const file = (args[0] ?? "").split("/").at(-1)!;
      if (INCLUDES[file] === undefined) fail(`unknown include ${args[0]}`);
      lines.push("include setup");
    } else if (command === "scroll") {
      lines.push(`${line} =${count(args[0]!)}`);
    } else lines.push(line);
  }
  return { state: state as ContentState, lines };
}

function main(): void {
  const root = process.argv[2];
  if (root === undefined) fail("usage: content-scripts <path to nokia-3310>");
  const dir = join(resolve(root), "captures/scripts");
  if (!existsSync(dir)) fail(`missing ${dir}`);
  const count = (prefix: string): number => {
    const shots = join(resolve(root), "captures/6.39", prefix);
    if (!existsSync(shots)) fail(`missing scroll ${shots}`);
    return readdirSync(shots).filter((name) => /^\d\d\.png$/.test(name)).length;
  };
  const scripts: Record<string, string> = {};
  const states: Record<string, ContentState> = {};
  for (const file of readdirSync(dir).sort()) {
    const section = /^v639-plan18c-(.+)\.cap$/.exec(file)?.[1];
    if (section === undefined) continue;
    const { state, lines } = transcribeContent(readFileSync(join(dir, file), "utf8"), count);
    scripts[`plan18c/${section}`] = lines.join("\n");
    states[`plan18c/${section}`] = state;
  }
  const entries = (table: Record<string, string>) =>
    Object.entries(table)
      .map(([name, value]) => `  ${JSON.stringify(name)}: ${JSON.stringify(value)},`)
      .join("\n");
  writeFileSync(
    OUT,
    [
      "// GENERATED by scripts/content-scripts.ts from captures/scripts/v639-plan18c-*.cap - do not edit",
      "// Plan 18c Task 0's capture command logs, one command per line (tests/support/18c-content.ts replays them).",
      "export const CONTENT_CAPTURE_SCRIPTS: Readonly<Record<string, string>> = {",
      entries(scripts),
      "};",
      "",
      "/** Each log's starting state (its `# state:` header). */",
      'export const CONTENT_CAPTURE_STATES: Readonly<Record<string, "virgin" | "factory" | "seccode">> = {',
      entries(states),
      "};",
      "",
    ].join("\n"),
  );
  console.log(`content-scripts: ${Object.keys(scripts).length} logs → ${OUT}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
