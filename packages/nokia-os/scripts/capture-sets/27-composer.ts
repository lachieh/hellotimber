export function composerTimelines(): CaptureSetEntry[] {
  return recordingDirs()
    .filter(lcdRecording)
    .map((dir) => ({
      id: composerTimelineId(dir),
      kind: "timeline",
      status: dir === "send/ok" ? SEND_PENDING : ASSERTED,
      prefer: {
        source: { kind: "recording", dir: `plan27/${dir}` },
        triggerFrame: 1,
        note: `plan27/${dir}: ${recordingNote(dir)}`,
      },
    }));
}

/** A recording's keys in words, for its golden's note. */
function recordingNote(dir: string): string {
  const row = COMPOSER_RECORDING_KEYS.find((r) => r.dir === dir);
  if (row === undefined) return "see COMPOSER_OTHER_RECORDINGS' scenario.";
  if (row.keys === "preview")
    return `the Ringing tone list, ▼ onto slot ${row.setup?.slice(-1)}'s entry.`;
  const before = row.before === "" ? "" : `${row.before}, then `;
  return `${row.from === "editor" ? `slot ${row.slot}'s editor` : row.from}${row.setup ? ` (${row.setup})` : ""}: ${before}${row.keys}.`;
}

export const COMPOSER_SOUNDS: readonly SoundCaptureEntry[] = recordingDirs()
  .filter(soundRecording)
  .map((dir) => {
    const row = COMPOSER_RECORDING_KEYS.find((r) => r.dir === dir);
    return {
      id: composerSoundId(dir),
      dir: `plan27/${dir}`,
      state: row?.state === "virgin" ? "virgin" : "factory",
      status: ASSERTED,
      note: `plan27/${dir}: ${recordingNote(dir)}`,
    };
  });

export function composerSounds(io: SoundCaptureIo): SoundGolden[] {
  return COMPOSER_SOUNDS.map((entry) => buildSoundGolden(entry, io));
}

