/** The still fixtures from `cases`, images in case order; checks images against cases. */
export function composerStills(
  cases: readonly ComposerCase[],
  images?: (dir: string) => readonly string[] | undefined,
): CaptureSetEntry[] {
  const files = new Map<string, string[]>();
  const named = new Set<string>();
  for (const { name } of cases) {
    if (named.has(name)) throw new ComposerCaptureError(`case ${name} is listed twice`);
    named.add(name);
    const { id } = stillFixtureOf(name);
    files.set(id, [...(files.get(id) ?? []), `plan27/${name}.png`]);
  }
  if (images !== undefined) {
    const dirs = new Set([...named].map((name) => name.slice(0, name.lastIndexOf("/"))));
    for (const dir of [...dirs].sort()) {
      const listed = images(`plan27/${dir}`);
      if (listed === undefined) continue;
      for (const stem of listed) {
        if (!named.has(`${dir}/${stem}`)) {
          throw new ComposerCaptureError(
            `image plan27/${dir}/${stem}.png has no case in COMPOSER_CASES`,
          );
        }
      }
      for (const name of named) {
        if (name.slice(0, name.lastIndexOf("/")) !== dir) continue;
        const stem = name.slice(name.lastIndexOf("/") + 1);
        if (/^\d+$/.test(stem) && !listed.includes(stem)) {
          throw new ComposerCaptureError(`case ${name} has no image plan27/${name}.png`);
        }
      }
    }
  }
  return [...files.entries()].map(([id, shots]) => {
    const dir = shots[0]!.slice("plan27/".length, shots[0]!.lastIndexOf("/"));
    const note = STILL_NOTES[dir];
    if (note === undefined) throw new ComposerCaptureError(`still directory ${dir} has no note`);
    return {
      id,
      kind: "still",
      status: ASSERTED,
      prefer: {
        source: { kind: "shots", files: shots },
        note: `${note} Each image's keys are its COMPOSER_CASES entry.`,
      },
    };
  });
}

/** Holds whose recordings become goldens: key 3 at every hold, every key at 1500 ms, the rest. */
function heldNote(dir: string): boolean {
  const note = /^hold\/note-(\d)-(\d+)$/.exec(dir);
  return note === null || note[1] === "3" || note[2] === "1500";
}

/** LCD timelines: the recordings whose screens the stills do not already hold. */
export function lcdRecording(dir: string): boolean {
  if (/^(open|leave|save|send|returns)\//.test(dir)) return true;
  if (dir.startsWith("tempo/done-")) return true;
  if (dir.startsWith("hold/")) return heldNote(dir);
  if (/^play\/(?!gate-|entry-|long-)/.test(dir)) return true;
  return dir === "ringing/choose" || dir === "restore/run";
}

/** Sound goldens: entry sounds, holds, the limit, Play, the sweeps and the previews. */
export function soundRecording(dir: string): boolean {
  if (dir.startsWith("sound/")) return true;
  if (dir.startsWith("hold/")) return heldNote(dir);
  return /^(limit|play)\//.test(dir);
}

/** The LCD fixture id of a recording (`composer/hold-note-3-750`). */
export function composerTimelineId(dir: string): string {
  return `composer/${slug(dir)}`;
}

/** The sound golden id of a recording (`sound/composer/entry-note`, `sound/composer/play-short`). */
export function composerSoundId(dir: string): string {
  return `sound/composer/${slug(dir.replace(/^sound\//, ""))}`;
}

