/** Where a case or a recording starts: an editor just opened, the slot list, standby. */
export type ComposerStart = "editor" | "slots" | "standby";
/** The image a case ran on: plan 15's factory image, the virgin image, the security-code image. */
export type ComposerState = "factory" | "virgin" | "seccode";

/**
 * One still: harness tokens from its start (`gen_v639_plan27.py` `play`): a key is a tap (≈42 ms
 * down, 250 ms settle, 300 ms gap: 592 ms), `k@1500` holds (then 250 ms), `k~60` presses 60 ms
 * (no settle), `+500` waits. An editor case's last `+<ms>` puts the shot in the cursor's shown
 * phase. The setup before the start: Menu 5 4 (and the slot's Select for `editor`), or
 * `COMPOSER_SETUPS[setup]`; `persist` and `restore` are a cold boot and Restore factory settings
 * (see the cases they follow).
 */
export interface ComposerCase {
  /** `<directory>/<image>` under plan27/. */
  readonly name: string;
  readonly from: ComposerStart;
  readonly state: ComposerState;
  /** The editor's slot (`from: "editor"`). */
  readonly slot?: number;
  readonly setup?: string;
  readonly keys: string;
}

/** A recording's keys: `before` (taps) from its start, then `keys` as raw edges (60 ms down). */
export interface ComposerRecordingKeys {
  /** The recording under plan27/. */
  readonly dir: string;
  readonly from: ComposerStart;
  readonly state: ComposerState;
  readonly slot?: number;
  readonly setup?: string;
  readonly before: string;
  /** `preview`: the preview recordings (a Ringing tone list moved onto the slot's entry). */
  readonly keys: string;
}

/** Menu 5 4 from a settled standby: the slot list on slot 1 (composer.inc). */
export const OPEN_COMPOSER = "menu +400 5 +300 4 +4500";
/** The slot list on slot 1 → slot k's editor: ▼ taps, a raw Select, 1440 ms. */
export function openSlot(k: number): string {
  return [...Array<string>(k - 1).fill("down"), "menu~60", "+1440"].join(" ");
}

