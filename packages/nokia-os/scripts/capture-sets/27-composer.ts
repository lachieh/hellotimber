/** A case or recording directory as a fixture id part (`cursor/up` → `cursor-up`). */
function slug(path: string): string {
  return path.replace(/\//g, "-");
}

/** The still fixture a case's image belongs to: one per capture directory. */
export function stillFixtureOf(name: string): { readonly id: string; readonly image: string } {
  const slash = name.lastIndexOf("/");
  if (slash < 0) throw new ComposerCaptureError(`composer case "${name}" has no directory`);
  return { id: `composer/${slug(name.slice(0, slash))}`, image: name.slice(slash + 1) };
}

