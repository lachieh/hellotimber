// Transcribe plan 30 Task 0's capture command logs for the acceptance scenarios (plan 30 Task 10).
//
//   mise exec -- vp run @hellotimber/nokia-os#sim-content-scripts /path/to/nokia-3310
//
// Reads `captures/scripts/v639-plan30-<section>.cap` (the exact command stream each capture
// section sent; `gen_v639_plan30.py`) and writes `scripts/generated/sim-content-scripts.ts`: each
// log's commands, one per line, without comments, indentation and `hex` (plan 18's
// `transcribe`), and each log's SIM fixture, toolkit and setup (its header's `# sim:`,
// `# toolkit:` and `# setup:`). Both setup includes become `include setup` (the replay's phone is
// virgin or factory by the log's setup). Tests replay these streams (tests/support/sim-content.ts),
// so they never read `$REF`.
//
// Idempotent. Runs under Node's type stripping: imports only node:*, sibling scripts.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { transcribe } from "./messages-scripts.ts";

const PACKAGE = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(PACKAGE, "scripts/generated/sim-content-scripts.ts");

function fail(message: string): never {
  console.error(`sim-content-scripts: ${message}`);
  process.exit(1);
}

function header(log: string, field: string, file: string): string {
  const value = new RegExp(`^# ${field}: (\\S+)$`, "m").exec(log)?.[1];
  if (value === undefined) fail(`${file}: no "# ${field}:" line`);
  return value;
}

function main(): void {
  const root = process.argv[2];
  if (root === undefined) fail("usage: sim-content-scripts <path to nokia-3310>");
  const dir = join(resolve(root), "captures/scripts");
  if (!existsSync(dir)) fail(`missing ${dir}`);
  const include = join(dir, "v639-setup.inc");
  if (!existsSync(include)) fail(`missing ${include}`);
  const setupLines = transcribe(readFileSync(include, "utf8"), []);
  const scripts: Record<string, string> = {};
  const setups: Record<string, { sim: string; toolkit?: string; setup: string }> = {};
  for (const file of readdirSync(dir).sort()) {
    const section = /^v639-plan30-(.+)\.cap$/.exec(file)?.[1];
    if (section === undefined) continue;
    // The factory include is plan 16's image and clock; the replay seeds the factory state.
    const log = readFileSync(join(dir, file), "utf8").replace(
      /^(\s*)include \S*v639-factory-setup\.inc$/m,
      "$1include v639-setup.inc",
    );
    const sim = header(log, "sim", file);
    const toolkit = header(log, "toolkit", file);
    const setup = header(log, "setup", file);
    scripts[`plan30/${section}`] = transcribe(log, setupLines).join("\n");
    setups[`plan30/${section}`] = {
      sim,
      ...(toolkit === "-" ? {} : { toolkit }),
      // `none`: the log powers the phone on itself (the boot sections); `imei-image`: plan 22's.
      setup: setup === "factory" || setup === "none" ? setup : "virgin",
    };
  }
  if (Object.keys(scripts).length === 0) fail(`no v639-plan30-*.cap in ${dir}`);
  const text = [
    "// GENERATED by scripts/sim-content-scripts.ts from captures/scripts/v639-plan30-*.cap - do not edit",
    "// Plan 30 Task 0's capture command logs, one command per line (tests/support/sim-content.ts replays them).",
    "export const SIM_CONTENT_CAPTURE_SCRIPTS: Readonly<Record<string, string>> = {",
    ...Object.entries(scripts).map(
      ([name, body]) => `  ${JSON.stringify(name)}: ${JSON.stringify(body)},`,
    ),
    "};",
    "",
    "/**",
    " * Each log's SIM fixture (`plan30/sims/<sim>.json`), applet script (`sims/stk-<toolkit>.json`)",
    " * and the state its phone starts in (`none`: the log powers it on itself).",
    " */",
    "export const SIM_CONTENT_SCRIPT_SETUPS: Readonly<",
    "  Record<",
    "    string,",
    "    {",
    "      readonly sim: string;",
    "      readonly toolkit?: string;",
    '      readonly setup: "virgin" | "factory" | "none";',
    "    }",
    "  >",
    "> = {",
    ...Object.entries(setups).map(
      ([name, { sim, toolkit, setup }]) =>
        `  ${JSON.stringify(name)}: { sim: ${JSON.stringify(sim)}, ${toolkit === undefined ? "" : `toolkit: ${JSON.stringify(toolkit)}, `}setup: ${JSON.stringify(setup)} },`,
    ),
    "};",
    "",
  ].join("\n");
  if (existsSync(OUT) && readFileSync(OUT, "utf8") === text) {
    console.log("sim-content-scripts: up to date");
    return;
  }
  writeFileSync(OUT, text);
  console.log(`sim-content-scripts: ${Object.keys(scripts).length} logs → ${OUT}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
