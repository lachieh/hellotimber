// Builds the T9 English dictionary (plan 18b D2, D3) from the open word-frequency list:
//
//   mise exec -- vp run @hellotimber/nokia-os#build-t9-dictionary <path-or-url>
//
// The input is IlyaSemenov/wikipedia-word-frequency's `results/enwiki-2023-04-13.txt` at the
// pinned commit (word, space, count per line, descending count; MIT). The script checks its
// SHA-256, keeps the first ENGLISH_SOURCE.limit words that pass `keepWord`, and writes
// `src/text/t9/generated/english.ts`: a provenance header and one exported string, the words in
// descending count, one per line, with a `#<w>` line wherever the weight w = floor(4 * log2(count))
// changes. Deterministic: running it twice gives no diff. No firmware data is read or written.
// Runs under Node's type stripping: imports only node:*.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** The pinned open list (plan 18b D2) and how many words the build keeps (D3). */
export interface DictionarySource {
  readonly repository: string;
  readonly file: string;
  readonly commit: string;
  readonly sha256: string;
  readonly licence: string;
  readonly limit: number;
}

export const ENGLISH_SOURCE: DictionarySource = {
  repository: "https://github.com/IlyaSemenov/wikipedia-word-frequency",
  file: "results/enwiki-2023-04-13.txt",
  commit: "798ea9062d6e5aed1fa87deeeda1cd99d5b37903",
  sha256: "e2071140a49a6c40c732bd68c36836ef13c0978233fb3d5e1b2a3c2d34faef59",
  licence: "MIT (c) 2015 Ilya Semenov",
  limit: 30000,
};

/** The pinned file's raw URL. */
export function sourceUrl(source: DictionarySource): string {
  const path = source.repository.replace("https://github.com/", "");
  return `https://raw.githubusercontent.com/${path}/${source.commit}/${source.file}`;
}

/** Lower-case a-z, at most one apostrophe and not at either end. */
const WORD = /^[a-z]+(?:'[a-z]+)?$/;

/** The D3 filter: a word of 1-32 characters as WORD, single letters only `a` and `i`. */
export function keepWord(word: string): boolean {
  if (!WORD.test(word) || word.length > 32) return false;
  return word.length > 1 || word === "a" || word === "i";
}

export interface CountedWord {
  readonly word: string;
  readonly count: number;
}

/** The first `limit` kept words of the list, in file order; throws naming a malformed line. */
export function selectWords(text: string, limit: number): CountedWord[] {
  const kept: CountedWord[] = [];
  const lines = text.split("\n");
  let previous = Number.POSITIVE_INFINITY;
  for (let i = 0; i < lines.length && kept.length < limit; i++) {
    const line = lines[i]!;
    if (line === "" && i === lines.length - 1) break;
    const match = /^(\S+) (\d+)$/.exec(line);
    if (match === null) throw new Error(`line ${i + 1}: expected "<word> <count>", got "${line}"`);
    const count = Number(match[2]);
    if (count > previous) throw new Error(`line ${i + 1}: counts must not increase`);
    previous = count;
    if (keepWord(match[1]!)) kept.push({ word: match[1]!, count });
  }
  return kept;
}

/** A word's weight: floor(4 * log2(count)); the engine ranks with 2^(w/4). */
export function weightOf(count: number): number {
  return Math.floor(4 * Math.log2(count));
}

/** The generated format: the words one per line, `#<w>` before each change of weight. */
export function formatDictionary(words: readonly CountedWord[]): string {
  const lines: string[] = [];
  let weight: number | undefined;
  for (const { word, count } of words) {
    const w = weightOf(count);
    if (w !== weight) lines.push(`#${w}`);
    weight = w;
    lines.push(word);
  }
  return lines.join("\n");
}

/** The generated module for the list's `bytes`; throws when they are not the pinned file. */
export function writeDictionaryModule(bytes: Uint8Array, source: DictionarySource): string {
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  if (sha256 !== source.sha256) {
    throw new Error(`SHA-256 mismatch: got ${sha256}, the pinned file is ${source.sha256}`);
  }
  const words = selectWords(new TextDecoder().decode(bytes), source.limit);
  return [
    "// GENERATED by scripts/build-t9-dictionary.ts - do not edit (plan 18b D3).",
    "//",
    `// Source: ${source.repository}`,
    `//   file ${source.file}`,
    `//   commit ${source.commit}`,
    `//   SHA-256 ${sha256}`,
    `// Licence: ${source.licence}; see ../THIRD_PARTY.md. Counts derived from English Wikipedia`,
    "// article text (April 2023 dump).",
    "// Filter: lower-case a-z, at most one apostrophe not first or last, 1-32 characters, single",
    `// letters only "a" and "i"; the first ${source.limit} kept words in descending count.`,
    `// ${words.length} words. Format: one word per line; "#<w>" sets the weight 2^(w/4) of the`,
    "// words after it, w = floor(4 * log2(count)).",
    "",
    `export const ENGLISH_T9_WORDS = \`${formatDictionary(words)}\n\`;`,
    "",
  ].join("\n");
}

const OUTPUT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "../src/text/t9/generated/english.ts",
);

async function readSource(from: string): Promise<Uint8Array> {
  if (!/^https?:\/\//.test(from)) return readFileSync(from);
  const response = await fetch(from);
  if (!response.ok) throw new Error(`${from}: HTTP ${response.status}`);
  return new Uint8Array(await response.arrayBuffer());
}

async function main(): Promise<void> {
  const from = process.argv[2];
  if (from === undefined) {
    console.error(
      `usage: build-t9-dictionary <path-or-url>\n  the pinned file: ${sourceUrl(ENGLISH_SOURCE)}`,
    );
    process.exit(1);
  }
  const module = writeDictionaryModule(await readSource(from), ENGLISH_SOURCE);
  let previous = "";
  try {
    previous = readFileSync(OUTPUT, "utf8");
  } catch {
    // first run
  }
  if (previous === module) console.log(`${OUTPUT}: up to date`);
  else {
    writeFileSync(OUTPUT, module);
    console.log(`wrote ${OUTPUT} (${module.length} bytes)`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error: unknown) => {
    console.error((error as Error).message);
    process.exit(1);
  });
}
