// Generate the harvester's text runs for plan 19's goldens (plan 19 Task 3).
//
//   mise exec -- vp run @hellotimber/nokia-os#phone-book-text-runs /path/to/nokia-3310
//
// Reads plan 19 Task 0's OCR (`plan19/text.json`) and its PNGs, and writes
// `scripts/generated/phone-book-text-runs.ts`: the runs of every image of every LCD golden in
// `goldens/index/19.json` but plan 22's call screens (matched to its capture by pixels; plan 14 Task 3's mapping),
// registered by `scripts/resource-inputs/19-phone-book.ts`.
//
// Idempotent. Runs under Node's type stripping: imports only node:*, sibling scripts.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseGolden } from "./golden-format.ts";
import { readPlanIndex } from "./golden-index.ts";
import type { TextRun } from "./harvest-glyphs.ts";
import { decodeLcdPng } from "./png.ts";
import { harvestRuns, type OcrRun } from "./tree-model.ts";

const PACKAGE = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const GOLDENS = join(PACKAGE, "goldens");
const OUT = join(PACKAGE, "scripts/generated/phone-book-text-runs.ts");

/**
 * OCR runs the harvester must not read, by text: art read as letters (the hatched bar's `I`s,
 * a cursor read as `ı`) is already dropped by `harvestRuns`.
 */
const NOT_TEXT = /^[ı]$/;

function fail(message: string): never {
  console.error(`phone-book-text-runs: ${message}`);
  process.exit(1);
}

function pixelKey(pixels: Uint8Array): string {
  return createHash("sha256").update(pixels).digest("hex");
}

/** OCR runs of every captured image under `captures/6.39/plan19/`, by pixels. */
function ocrByPixels(root: string): Map<string, OcrRun[]> {
  const path = join(root, "plan19", "text.json");
  if (!existsSync(path)) fail(`missing ${path}: run plan 19's Task 0 OCR`);
  const ocr = JSON.parse(readFileSync(path, "utf8")) as Record<string, OcrRun[]>;
  const out = new Map<string, OcrRun[]>();
  for (const rel of Object.keys(ocr).sort()) {
    const png = join(root, "plan19", rel);
    if (!existsSync(png)) continue;
    const key = pixelKey(decodeLcdPng(readFileSync(png), png));
    if (!out.has(key)) out.set(key, ocr[rel]!);
  }
  return out;
}

function main(): void {
  const ref = process.argv[2];
  if (!ref) fail("usage: phone-book-text-runs <REF> (the nokia-3310 capture corpus directory)");
  const root = join(resolve(ref), "captures/6.39");
  if (!existsSync(root)) fail(`missing ${root}: pass the nokia-3310 corpus directory as REF`);
  const ocr = ocrByPixels(root);

  const out: Record<string, Record<string, TextRun[]>> = {};
  for (const entry of readPlanIndex(GOLDENS, "19")) {
    if (entry.kind !== "still" && entry.kind !== "timeline") continue;
    // Plan 22's call screens: their icons and thin `…` are plan 22's to harvest.
    if (entry.status === "pending:22") continue;
    const golden = parseGolden(readFileSync(join(GOLDENS, entry.file), "utf8"), entry.file);
    const images: Record<string, TextRun[]> = {};
    for (const image of golden.images) {
      const found = ocr.get(pixelKey(image.pixels));
      if (found === undefined) fail(`${entry.id} image "${image.name}": no OCR'd capture`);
      const runs = harvestRuns(
        found.filter((run) => !NOT_TEXT.test(run.text.trim())),
        `${entry.id} ${image.name}`,
      );
      if (runs.length > 0) images[image.name] = runs;
    }
    if (Object.keys(images).length > 0) out[entry.id] = images;
  }

  const text =
    `// GENERATED by scripts/phone-book-text-runs.ts from goldens/ and plan19/text.json - do not edit\n` +
    `// Text runs of every plan 19 golden image, registered by resource-inputs/19-phone-book.ts.\n` +
    `export const PHONE_BOOK_TEXT_RUNS: Readonly<Record<string, Readonly<Record<string, readonly {\n` +
    `  readonly font: "small" | "large" | "digits" | "thin";\n  readonly text: string;\n` +
    `  readonly top: number;\n  readonly inverted?: boolean;\n  readonly left?: number;\n` +
    `  readonly right?: number;\n}[]>>>> = {\n` +
    Object.entries(out)
      .map(
        ([id, images]) =>
          `  ${JSON.stringify(id)}: {\n` +
          Object.entries(images)
            .map(([name, runs]) => `    ${JSON.stringify(name)}: ${JSON.stringify(runs)},\n`)
            .join("") +
          `  },\n`,
      )
      .join("") +
    `};\n`;
  mkdirSync(dirname(OUT), { recursive: true });
  if (existsSync(OUT) && readFileSync(OUT, "utf8") === text) {
    console.log("phone-book-text-runs: up to date");
    return;
  }
  writeFileSync(OUT, text);
  console.log(
    `phone-book-text-runs: ${Object.keys(out).length} goldens, ${Object.values(out).reduce((n, i) => n + Object.keys(i).length, 0)} images`,
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
