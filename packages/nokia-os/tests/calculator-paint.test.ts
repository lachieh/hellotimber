describe("calculator screen", () => {
  it.each(DISPLAY)("%s %s: %j", (id, image, lines) => {
    const fb = new Framebuffer();
    paintWidget(fb, { kind: "calculator", screen: "display", lines, softkey: "Options" });
    expectLcd(fb, goldenImage(id, image), lines.join(" "));
  });

  it("covers one, two and three lines, signs, points and every operator", () => {
    const shown = DISPLAY.map(([, , lines]) => lines);
    for (const count of [1, 2, 3]) expect(shown.some((l) => l.length === count)).toBe(true);
    for (const op of ["+", "-", "*", "/"]) expect(shown.some((l) => l[1] === op)).toBe(true);
    expect(shown.some((l) => l[0] === "-123456789")).toBe(true);
    expect(shown.some((l) => l[0] === "0.0012345")).toBe(true);
  });

  it("throws on a line that does not fit and on more than three lines (plan 13 D10)", () => {
    const paint = (lines: readonly string[]) =>
      paintWidget(new Framebuffer(), {
        kind: "calculator",
        screen: "display",
        lines,
        softkey: "Options",
      });
    expect(() => paint(["1234567890123456"])).toThrow("px wide");
    expect(() => paint(["1", "+", "2", "3"])).toThrow("1-3 lines");
  });
});

describe("rate entry (D7)", () => {
  it.each(RATE)("%s %s: %s, cursor at %d, shown %s", (id, image, text, cursorAt, cursor) => {
    const fb = new Framebuffer();
    paintWidget(fb, {
      kind: "calculator",
      screen: "rate",
      label: "Exchange rate:",
      text,
      cursorAt,
      cursor,
      softkey: "OK",
    });
    expectLcd(fb, goldenImage(id, image), `${text} |${cursorAt} ${cursor ? "cursor" : "plain"}`);
  });

  it("compares both blink phases at the start, inside and at the end of the value", () => {
    for (const shown of [true, false]) {
      expect(
        RATE.some(([, , text, at, c]) => at === 0 && text !== "" && c === shown) || !shown,
      ).toBe(true);
      expect(RATE.some(([, , text, at, c]) => at > 0 && at < text.length && c === shown)).toBe(
        true,
      );
      expect(RATE.some(([, , text, at, c]) => at === text.length && c === shown)).toBe(true);
    }
  });
});
