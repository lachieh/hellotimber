/**
 * Traces the bezel's opening over the LCD out of the GLB into `src/lcd-opening.generated.ts`: a
 * signed distance field over the display plane, negative where the plane shows from the front
 * (inside the opening) and positive where the bezel covers it. The LCD's bezel shadow
 * (Nokia3310.tsx) reads it to know where the lip is. Run after changing the model:
 * `vp run @hellotimber/phone-3d#lcd-opening`.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadModel, rasterise } from "./model.ts";

const OUT = new URL("../src/lcd-opening.generated.ts", import.meta.url);

/** The front view's cell, in stage units (the phone is 10 tall): finer than the field. */
const CELL = 0.004;
/** The field's samples across the display plane, and up it. */
const COLUMNS = 128;
const ROWS = 96;
/** The farthest distance the field holds, in stage units; past it, it holds this. */
const RANGE = 1;

async function main() {
  const { parts, center, scale } = await loadModel();
  const screen = parts.find((part) => part.name === "screen");
  if (screen === undefined) throw new Error("the model has no screen");
  // The display plane's bounds, in stage units.
  const [minX, maxX, minY, maxY] = [0, 0, 1, 1].map((axis, i) =>
    (i % 2 === 0 ? Math.min : Math.max)(...screen.points.map((p) => p[axis]!)),
  ) as [number, number, number, number];
  const raster = rasterise(parts, { minX, maxX, minY, maxY }, CELL);
  const screenId = parts.indexOf(screen);
  const open = (x: number, y: number) =>
    x >= 0 && y >= 0 && x < raster.width && y < raster.height
      ? raster.owner[y * raster.width + x] === screenId
      : false;

  // The opening's edge: midway between each pair of neighbouring cells either side of it.
  const edge: [number, number][] = [];
  for (let y = 0; y < raster.height; y++)
    for (let x = 0; x < raster.width; x++) {
      if (open(x, y) !== open(x + 1, y)) edge.push([raster.toX(x + 1), raster.toY(y + 0.5)]);
      if (open(x, y) !== open(x, y + 1)) edge.push([raster.toX(x + 0.5), raster.toY(y + 1)]);
    }

  const distances = new Int8Array(COLUMNS * ROWS);
  for (let row = 0; row < ROWS; row++)
    for (let column = 0; column < COLUMNS; column++) {
      // Texel centres, as the GPU samples them.
      const x = minX + ((column + 0.5) / COLUMNS) * (maxX - minX);
      const y = minY + ((row + 0.5) / ROWS) * (maxY - minY);
      let nearest = Infinity;
      for (const [ex, ey] of edge) nearest = Math.min(nearest, Math.hypot(ex - x, ey - y));
      const inside = open(
        Math.floor((x - raster.toX(0)) / CELL),
        Math.floor((y - raster.toY(0)) / CELL),
      );
      const d = Math.min(RANGE, nearest) * (inside ? -1 : 1);
      distances[row * COLUMNS + column] = Math.round((d / RANGE) * 127);
    }

  // In the display plane's local space: the GLB's units, before the stage's scale.
  const local = (v: number, axis: 0 | 1) => v / scale + center[axis]!;
  const field = {
    x: local(minX, 0),
    y: local(minY, 1),
    width: (maxX - minX) / scale,
    height: (maxY - minY) / scale,
    columns: COLUMNS,
    rows: ROWS,
    range: RANGE / scale,
  };
  const body = `// Generated by scripts/lcd-opening.ts from public/models/nokia3310-v3.glb. Do not edit.

/**
 * The bezel's opening over the display plane, as a signed distance field in the plane's local
 * space: \`columns\` × \`rows\` samples over the rectangle at \`x\`, \`y\` (\`width\` × \`height\`),
 * row 0 at the bottom. Each is a signed byte, times \`range\` / 127: negative inside the opening.
 */
export const LCD_OPENING = {
  ...${JSON.stringify(field)},
  distances: "${Buffer.from(distances.buffer).toString("base64")}",
} as const;
`;
  writeFileSync(OUT, body);
  console.log(`wrote ${fileURLToPath(OUT)}: ${edge.length} edge points, ${body.length} chars`);
}

await main();
